#!/usr/bin/env bash
# ==================================================================
#  msf-import-sharkjack.sh
#  Description : SCP loot files from Shark Jack, import relevant
#                XML/gnmap/nmap scan results into Metasploit's
#                database via msfconsole, and open a console.
#  Requires    : ssh/scp, msfconsole (Metasploit Framework)
#  Usage       : ./msf-import-sharkjack.sh [shark_ip] [loot_dir_on_device]
#  Defaults    : 172.16.24.1   /root/loot
#  Example     : ./msf-import-sharkjack.sh 172.16.24.1 /root/loot
# ==================================================================

set -euo pipefail

SHARK_IP="${1:-172.16.24.1}"
REMOTE_LOOT="${2:-/root/loot}"
SHARK_USER="root"
LOCAL_LOOT="./loot/sharkjack-$(date +%Y%m%d_%H%M%S)"
mkdir -p "$LOCAL_LOOT"

echo " =================================================="
echo "  Shark Jack → Metasploit Import"
echo "  Shark IP   : $SHARK_IP"
echo "  Remote dir : $REMOTE_LOOT"
echo "  Local dir  : $LOCAL_LOOT"
echo " =================================================="

# Verify Shark Jack reachable
if ! ssh -o ConnectTimeout=5 -o BatchMode=yes "${SHARK_USER}@${SHARK_IP}" true 2>/dev/null; then
    echo "[!] Cannot reach Shark Jack at ${SHARK_IP}."
    echo "    Connect via ATTACK mode and ensure SSH key is deployed."
    exit 1
fi
echo "[*] Shark Jack reachable."

# List remote loot
echo "[*] Remote loot contents:"
ssh "${SHARK_USER}@${SHARK_IP}" "find ${REMOTE_LOOT} -type f 2>/dev/null | sort" 2>/dev/null | \
    tee "${LOCAL_LOOT}/remote_manifest.txt"

# SCP all loot
echo ""
echo "[*] Pulling loot..."
scp -r "${SHARK_USER}@${SHARK_IP}:${REMOTE_LOOT}/" "${LOCAL_LOOT}/device-loot/" 2>/dev/null || {
    echo "[!] SCP failed. Trying individual file copy..."
    mkdir -p "${LOCAL_LOOT}/device-loot"
    while IFS= read -r rfile; do
        scp "${SHARK_USER}@${SHARK_IP}:${rfile}" "${LOCAL_LOOT}/device-loot/" 2>/dev/null || true
    done < "${LOCAL_LOOT}/remote_manifest.txt"
}
echo "[+] Loot pulled to: ${LOCAL_LOOT}/device-loot/"

# Find importable scan files
NMAP_XML=$(find "${LOCAL_LOOT}" -name "*.xml" 2>/dev/null | head -20)
GNMAP=$(find "${LOCAL_LOOT}" -name "*.gnmap" 2>/dev/null | head -20)
NMAP_PLAIN=$(find "${LOCAL_LOOT}" -name "*.nmap" 2>/dev/null | head -20)

# Verify msfconsole available
if ! command -v msfconsole >/dev/null 2>&1; then
    echo "[!] msfconsole not found."
    echo "    Install Metasploit: https://github.com/rapid7/metasploit-framework"
    echo "[+] Loot available at: $LOCAL_LOOT"
    exit 1
fi

# Build msfconsole import script
MSF_RC="${LOCAL_LOOT}/import.rc"
{
    echo "# Auto-generated by msf-import-sharkjack.sh"
    echo "db_status"
    echo ""

    if [[ -n "$NMAP_XML" ]]; then
        while IFS= read -r f; do
            echo "db_import $f"
        done <<< "$NMAP_XML"
    fi

    if [[ -n "$GNMAP" ]]; then
        while IFS= read -r f; do
            echo "db_import $f"
        done <<< "$GNMAP"
    fi

    echo ""
    echo "hosts"
    echo "services"
    echo ""
    echo "vulns"
} > "$MSF_RC"

echo ""
echo "[*] Generated Metasploit RC script: $MSF_RC"

# Count importable files
IMPORT_COUNT=$(( $(echo "$NMAP_XML" | grep -c . || echo 0) + $(echo "$GNMAP" | grep -c . || echo 0) ))
echo "[*] Files to import: $IMPORT_COUNT"

if [[ $IMPORT_COUNT -eq 0 ]]; then
    echo "[!] No nmap XML or gnmap files found to import."
    echo "    Ensure Shark Jack payload ran nmap with -oA or -oX flags."
    echo "[+] Loot still available at: $LOCAL_LOOT"
    exit 0
fi

echo ""
echo "[*] Starting msfconsole and importing..."
echo "    (This will open an interactive Metasploit console after import)"
echo ""

msfconsole -q -r "$MSF_RC"
