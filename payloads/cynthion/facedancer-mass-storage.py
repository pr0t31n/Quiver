#!/usr/bin/env python3
"""
facedancer-mass-storage.py
Description : Emulate a USB mass storage device with a custom disk image
              using Facedancer (Cynthion or GreatFET). Tests autorun
              restrictions and USB storage policy controls.
              Generates a small FAT32 image with a test payload file.
Requires    : facedancer, Cynthion or GreatFET One
Usage       : python3 facedancer-mass-storage.py [image_file]
Note        : Only tests policy controls — does not execute any code on the host.
"""

import sys
import os
import time
from datetime import datetime

try:
    from facedancer import FacedancerUSBApp
    from facedancer.devices.mass_storage import USBMassStorageDevice
except ImportError:
    print("[!] facedancer not found. Install with: pip install facedancer")
    sys.exit(1)

LOOT_DIR = f"./loot/usb-storage-{datetime.now().strftime('%Y%m%d_%H%M%S')}"
os.makedirs(LOOT_DIR, exist_ok=True)

# Create a simple FAT32 disk image if not provided
IMAGE_FILE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(LOOT_DIR, "test_disk.img")

if not os.path.exists(IMAGE_FILE):
    print(f"[*] Creating test disk image: {IMAGE_FILE} (64MB)")
    os.system(f"dd if=/dev/zero of={IMAGE_FILE} bs=1M count=64 2>/dev/null")
    os.system(f"mkfs.fat -F 32 {IMAGE_FILE} 2>/dev/null || mkdosfs -F 32 {IMAGE_FILE} 2>/dev/null || true")
    # Mount and add test file
    MOUNT_TMP = "/tmp/facedancer_test_mount"
    os.makedirs(MOUNT_TMP, exist_ok=True)
    if os.system(f"mount -o loop {IMAGE_FILE} {MOUNT_TMP} 2>/dev/null") == 0:
        with open(os.path.join(MOUNT_TMP, "AUTORUN.INF"), 'w') as f:
            f.write("[AutoRun]\nopen=test.bat\n")
        with open(os.path.join(MOUNT_TMP, "test.bat"), 'w') as f:
            f.write("@echo Test file - autorun not blocked!\r\n")
        with open(os.path.join(MOUNT_TMP, "README.txt"), 'w') as f:
            f.write("USB Mass Storage Policy Test\nGenerated by facedancer-mass-storage.py\n")
        os.system(f"umount {MOUNT_TMP} 2>/dev/null || true")
    print(f"[+] Image created with AUTORUN.INF test file")

print(f" ==================================================")
print(f"  Facedancer — USB Mass Storage Emulation")
print(f"  Image: {IMAGE_FILE}")
print(f" ==================================================")
print("[*] Connect Facedancer to target host, press Enter to start...")
input()

print("[*] Emulating USB mass storage device...")
print("    Watch target host for:")
print("    - Autorun execution (Windows XP/7 unpatched)")
print("    - Drive mount notification")
print("    - DLP/security software alerts")
print("    Press Ctrl+C to stop")

try:
    app = FacedancerUSBApp(verbose=1)
    dev = USBMassStorageDevice(app, disk_image=IMAGE_FILE)
    app.run()
except KeyboardInterrupt:
    print("\n[+] Emulation stopped.")
except Exception as e:
    print(f"[!] Error: {e}")
